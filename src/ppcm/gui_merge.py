"""Merged GUI files and types: every Prosper or Perish (PP) change and every Construction Manager (CM) change shows.

Load order of the playset: Community Mod Framework (CMF), PP, CM, this patch. The engine's rules this step builds on:

- A file at the same relative path: the last mod's file replaces the others entirely, its types and templates too.
  PP and CM both ship ``in_game/gui/location_window.gui`` and ``in_game/gui/building_view.gui``, so CM's copies hide
  PP's. The patch ships a merged copy of every such file (found automatically, see ``same_path_files``).
- A GUI ``type`` or ``template`` defined in several files: the last definition in load order wins everywhere (across
  mods, files load in mod order, not by path). Types both mods define in different files (the build panel, the food
  view) are merged into one patch file, ``in_game/gui/ppcm_merged_types.gui``, which wins because the patch loads last.
- CMF re-declares the vanilla types of the windows it extracts (``gui/vanilla/cmf_*_vanilla_types.gui``), so CM's
  ``location_window.gui`` keeps only the window and the types it changes. A type CM's file leaves out therefore counts
  as "CM did not change it" (only when CMF declares it; otherwise the build stops).
- PP protects vanilla types it changes by copies named ``pp_<vanilla name>`` that its windows instantiate
  (``location_card``, ``food_production_province``: constructor ``gui_compat.py``; the production view's rows
  ``location_filtered_header_*``: ``tools/port_vanilla_gui.py``). A copy is merged like the type it copies (base the
  vanilla type, theirs CM's version of it), so it carries CM's change to that type too.

Merge method: each part (a type, a template, a top-level window) is merged on its own, 3-way, with vanilla's version
of the part as base, PP's as ours and CM's as theirs (``merge3``: a line diff, patience anchors, whitespace and blank
lines are no change). The merged file keeps PP's structure (all its types and templates), since it replaces both
mods' files. A conflict is resolved only by a named rule (``HUNK_RULES`` for any part, ``PART_RULES`` for a part both
mods rebuilt); any other conflict stops the build with the hunk printed, because the patch is rebuilt after every
update of either mod. A clean line merge can still nest wrongly where one mod moves a box boundary inside a block the
other rebuilt (closing braces all look alike), so ``check_nesting`` stops the build when a box is opened by one mod's
line and closed by the other's. Every output is parsed again (balanced braces, closed strings) before it is returned,
and each generated file lists the rules that resolved something in it.
"""

