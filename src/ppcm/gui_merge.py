# line diff and 3-way merge


def _norm(line: str) -> str:
    return " ".join(line.split())


def _solid(lines: list[str]) -> list[str]:
    return [x for x in (_norm(line) for line in lines) if x]


def _lis(seq: list[tuple[int, int]]) -> list[tuple[int, int]]:
    """Longest subsequence increasing in the second element (the first already increases)."""
    tails: list[int] = []
    idx: list[int] = []
    prev = [-1] * len(seq)
    for n, (_, j) in enumerate(seq):
        p = bisect.bisect_left(tails, j)
        if p == len(tails):
            tails.append(j)
            idx.append(n)
        else:
            tails[p] = j
            idx[p] = n
        prev[n] = idx[p - 1] if p else -1
    out = []
    n = idx[-1] if idx else -1
    while n >= 0:
        out.append(seq[n])
        n = prev[n]
    return out[::-1]


def pairs(a: list[str], b: list[str]) -> list[tuple[int, int]]:
    """Matched line pairs (i, j), increasing in both: patience diff (lines unique on both sides as anchors), difflib
    in the gaps without such lines."""
    out: list[tuple[int, int]] = []
    work: list = [("range", 0, len(a), 0, len(b))]  # an explicit stack instead of recursion: ranges and pairs
    while work:
        item = work.pop()
        if item[0] == "pair":
            out.append((item[1], item[2]))
            continue
        _, alo, ahi, blo, bhi = item
        head = []
        while alo < ahi and blo < bhi and a[alo] == b[blo]:
            head.append((alo, blo))
            alo += 1
            blo += 1
        tail = []
        while alo < ahi and blo < bhi and a[ahi - 1] == b[bhi - 1]:
            ahi -= 1
            bhi -= 1
            tail.append((ahi, bhi))
        seq_items: list = [("pair", i, j) for i, j in head]
        if alo < ahi and blo < bhi:
            ca = Counter(a[alo:ahi])
            cb = Counter(b[blo:bhi])
            pos_b = {b[j]: j for j in range(blo, bhi) if b[j] and cb[b[j]] == 1 and ca[b[j]] == 1}
            anchors = _lis([(i, pos_b[a[i]]) for i in range(alo, ahi) if a[i] in pos_b])
            if anchors:
                pa, pb = alo, blo
                for i, j in anchors:
                    seq_items.append(("range", pa, i, pb, j))
                    seq_items.append(("pair", i, j))
                    pa, pb = i + 1, j + 1
                seq_items.append(("range", pa, ahi, pb, bhi))
            else:
                sm = SequenceMatcher(None, a[alo:ahi], b[blo:bhi], autojunk=False)
                for i, j, n in sm.get_matching_blocks():
                    seq_items.extend(("pair", alo + i + d, blo + j + d) for d in range(n))
        seq_items.extend(("pair", i, j) for i, j in reversed(tail))
        work.extend(reversed(seq_items))
    return out


@dataclass
class Hunk:
    """One conflict: vanilla's lines and what each mod made of them, with the merged lines around it."""

    where: str  # file and part
    base_start: int  # index of the first base line in the part's base text
    base: list[str]
    ours: list[str]  # PP
    theirs: list[str]  # CM
    before: list[str]
    after: list[str]


def merge3_tagged(base: list[str], ours: list[str], theirs: list[str], where: str, resolve) -> list[tuple[str, str]]:
    """3-way line merge. Whitespace and blank lines are no change. A region both sides changed differently is a
    conflict, handed to resolve(hunk) -> [(line, origin)]. Every output line comes with its origin: "=" (vanilla's,
    or a change both made the same way), "pp" or "cm"."""
    kb, ko, kt = ([_norm(x) for x in s] for s in (base, ours, theirs))
    mo = dict(pairs(kb, ko))
    mt = dict(pairs(kb, kt))
    sync = [(i, mo[i], mt[i]) for i in range(len(base)) if i in mo and i in mt]
    sync.append((len(base), len(ours), len(theirs)))
    out: list[tuple[str, str]] = []
    bz = oz = tz = 0
    for bi, oi, ti in sync:
        b, o, t = base[bz:bi], ours[oz:oi], theirs[tz:ti]
        if b or o or t:
            sb, so, st = _solid(b), _solid(o), _solid(t)
            if st == sb or st == so:
                out.extend((x, "pp" if so != sb else "=") for x in o)  # CM did not change it (blanks aside), or the same way
            elif so == sb:
                out.extend((x, "cm") for x in t)  # only CM changed it
            else:
                out.extend(resolve(Hunk(where, bz, b, o, t, [x for x, _ in out[-6:]], base[bi:bi + 6])))
        if bi < len(base):
            out.append((ours[oi], "="))
        bz, oz, tz = bi + 1, oi + 1, ti + 1
    return out


def merge3(base: list[str], ours: list[str], theirs: list[str], where: str, resolve) -> list[str]:
    return [x for x, _ in merge3_tagged(base, ours, theirs, where, resolve)]


def check_nesting(tagged: list[tuple[str, str]], where: str) -> None:
    """Stop when one mod's line closes (or opens) a box whose other brace is the other mod's line. Closing braces all
    look alike to a line diff, so there it cannot tell which box a change belongs in (for example CM moving a box out
    of a block that PP rebuilt): such a merge balances but nests wrongly. Each box must be opened and closed by one
    side, or by vanilla's lines."""
    text = "".join(x for x, _ in tagged)
    d = Doc(text, where)
    starts = [0]
    for x, _ in tagged:
        starts.append(starts[-1] + len(x))
    line_of = [bisect.bisect_right(starts, t.start) - 1 for t in d.toks]
    origin = [o for _, o in tagged]
    for k, t in enumerate(d.toks):
        if t.kind != "{":
            continue
        a, b = line_of[k], line_of[d.match[k]]
        if {origin[a], origin[b]} == {"pp", "cm"}:
            raise GuiMergeError(
                f"GUI merge conflict in {where}: the box opened at merged line {a + 1} by {origin[a].upper()} "
                f"({tagged[a][0].strip()}) is closed at line {b + 1} by {origin[b].upper()}: one mod's change nests "
                f"into a box the other one rebuilt. Add a rule for it in src/ppcm/gui_merge.py (PART_RULES).")


def edits(base: list[str], side: list[str]) -> list[tuple[int, int, int, int]]:
    """The changes of one side against base as (b0, b1, s0, s1): base[b0:b1] became side[s0:s1]; whitespace-only
    changes left out."""
    kb, ks = [_norm(x) for x in base], [_norm(x) for x in side]
    out = []
    pb = ps = 0
    for i, j in pairs(kb, ks) + [(len(base), len(side))]:
        if (i > pb or j > ps) and _solid(base[pb:i]) != _solid(side[ps:j]):
            out.append((pb, i, ps, j))
        pb, ps = i + 1, j + 1
    return out


def _describe(h: Hunk, why: str = "no rule covers it") -> str:
    def block(label: str, lines: list[str]) -> str:
        return "".join(f"  {label:6s}| {x.rstrip()}\n" for x in lines) or f"  {label:6s}| (nothing)\n"

    return (
        f"GUI merge conflict in {h.where} ({why}).\n"
        + block("before", h.before[-3:]) + block("van", h.base) + block("PP", h.ours) + block("CM", h.theirs)
        + block("after", h.after[:3])
        + "Add a rule for it in src/ppcm/gui_merge.py (HUNK_RULES or PART_RULES), keyed to what the two changes are."
    )


