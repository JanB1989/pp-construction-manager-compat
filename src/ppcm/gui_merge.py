def part_pp_row_header(base: str, ours: str, theirs: str, where: str, log: list[str]) -> tuple[str, set[str], set[str]]:
    """PP's copy of location_filtered_header_with_candidate (a built building's row in PP's location view).

    PP rebuilt the row's efficiency into columns; CM (GlorpUI) moves a box out of that very block to stack an ROI
    line under the efficiency, which a line merge nests into PP's first column. Rule: CM's changes are carried one
    group at a time by ROW_HEADER_CM_CHANGES (the auto-expand button yes, the ROI line and its compaction no), then
    the line merge runs on vanilla plus the carried groups."""
    b, t = base.splitlines(True), theirs.splitlines(True)
    picked: list[tuple[str, str]] = []
    cm_dropped: set[str] = set()
    out: list[str] = []
    at = 0
    for b0, b1, s0, s1 in _group_ranges(b, t):
        removed, added = "".join(b[b0:b1]), "".join(t[s0:s1])
        name, _, carry, why = _classify(ROW_HEADER_CM_CHANGES, removed, added, where, "CM", "part_pp_row_header / ROW_HEADER_CM_CHANGES")
        out.extend(b[at:b0])
        out.extend(t[s0:s1] if carry else b[b0:b1])
        at = b1
        picked.append((name, why))
        if not carry:
            cm_dropped |= identifiers(added) - identifiers(removed)
    out.extend(b[at:])
    selected = "".join(out)
    check_gui(selected, f"CM's carried changes, {where}")
    for name, why in dict(picked).items():
        log.append(f"{where}: CM's {name}: {why}")
    tagged = merge3_tagged(b, ours.splitlines(True), selected.splitlines(True), where, lambda h: resolve_default(h, log))
    check_nesting(tagged, where)
    return "".join(x for x, _ in tagged), set(), cm_dropped


