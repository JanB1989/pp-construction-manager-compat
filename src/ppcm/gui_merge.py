# rules for parts both mods rebuilt (key -> function(base, ours, theirs, where, log) -> (text, pp_dropped))


def _numbers_only(a: list[str], b: list[str]) -> bool:
    """The lines differ only in numbers (comments ignored)."""

    def shape(lines):
        return [re.sub(r"\d+", "0", _norm(x.split("#", 1)[0])) for x in lines if _norm(x.split("#", 1)[0])]

    return shape(a) == shape(b)


def _block(doc: Doc, head: tuple[str, ...]) -> Stmt:
    found = [s for s in doc.walk() if s.head == head and s.block]
    if len(found) != 1:
        raise GuiMergeError(f"{doc.label}: expected one '{' '.join(head)}' block, found {len(found)}")
    return found[0]


def _sizes(doc: Doc, s: Stmt) -> list[tuple[str, list[str]]]:
    """addrow and size statements below s, in order: (name, values)."""
    out = []
    for c in doc.walk(s):
        if c.head == ("addrow", "=", c.head[-1]) and not c.block:
            out.append(("addrow", [c.head[2]]))
        elif c.head == ("size", "=") and c.block:
            out.append(("size", [doc.word(k) for k in range(c.block[0] + 1, c.block[1])]))
    return out


def part_build_list_rows(base: str, ours: str, theirs: str, where: str, log: list[str]) -> tuple[str, set[str], set[str]]:
    """build_location_lateralview_panel_content (the build panel's list).

    PP replaced vanilla's list ("scroll_list_content") by its own layout ("scroll_list_layout": the selected sort or
    the payback order, a copy of vanilla's row in every payback band); CM kept vanilla's list and only shrank its rows
    for CM's 46-high entry (rows 60 -> 56, entries 58 -> 54). Rule: PP's layout, and CM's row heights in every row PP
    draws. Elsewhere the line merge applies (CM's mass auto-expand buttons in the header, PP's sort buttons)."""
    db, dt = Doc(base, "vanilla " + where), Doc(theirs, "CM " + where)
    slot = ("blockoverride", '"scroll_list_content"')
    vb, vt = _block(db, slot), _block(dt, slot)
    lb, lt = db.line(db.toks[vb.first].start) - 1, db.line(db.toks[vb.last].start)  # base lines of vanilla's list
    rows_b, rows_t = _sizes(db, vb), _sizes(dt, vt)
    if [n for n, _ in rows_b] != [n for n, _ in rows_t] or any(len(x) != len(y) for (_, x), (_, y) in zip(rows_b, rows_t)):
        raise GuiMergeError(f"{where}: CM's list rows no longer match vanilla's shape: {rows_t} vs {rows_b}")
    heights: dict[tuple[str, str], str] = {}  # (statement, vanilla height) -> CM height
    for (name, vals_b), (_, vals_t) in zip(rows_b, rows_t):
        for x, y in zip(vals_b, vals_t):
            if x != y:
                if (name, x) in heights and heights[(name, x)] != y:
                    raise GuiMergeError(f"{where}: CM maps vanilla's {name} {x} to two values")
                heights[(name, x)] = y

    def resolve(h: Hunk) -> list[tuple[str, str]]:
        inside = lb <= h.base_start and h.base_start + len(h.base) <= lt
        if inside and _numbers_only(h.base, h.theirs):
            log.append(f"{where}, vanilla line {h.base_start + 1}: PP's list layout, CM's row heights applied below")
            return [(x, "pp") for x in h.ours]
        return resolve_default(h, log)

    tagged = merge3_tagged(base.splitlines(True), ours.splitlines(True), theirs.splitlines(True), where, resolve)
    check_nesting(tagged, where)
    merged = "".join(x for x, _ in tagged)
    if not heights:
        return merged, set(), set()  # CM keeps vanilla's rows: nothing to carry into PP's
    dm = Doc(merged, "merged " + where)
    layout = _block(dm, ("blockoverride", '"scroll_list_layout"'))
    repl: list[tuple[int, int, str]] = []
    rows = 0
    for s in dm.walk(layout):
        if "using = build_location_entry" not in _norm(dm.raw(s)) or not s.block:
            continue
        for c in dm.inner(s):  # the row's own size statements (its outer widget and the entry's widget)
            if c.head == ("addrow", "=", c.head[-1]) and not c.block and ("addrow", c.head[2]) in heights:
                k = c.last
                repl.append((dm.toks[k].start, dm.toks[k].end, heights[("addrow", c.head[2])]))
            elif c.head == ("size", "=") and c.block and c.block[1] - c.block[0] == 3:
                k = c.block[0] + 2  # the height
                new = heights.get(("size", dm.word(k)))
                if new:
                    repl.append((dm.toks[k].start, dm.toks[k].end, new))
                    rows += 1
    if not rows:
        raise GuiMergeError(f"{where}: no row of PP's list layout found to take CM's row heights")
    for a, b, new in sorted(set(repl), reverse=True):
        merged = merged[:a] + new + merged[b:]
    log.append(f"{where}: CM's row heights ({', '.join(f'{n} {x}->{y}' for (n, x), y in sorted(heights.items()))}) "
               f"set in {rows} sizes of PP's list rows")
    return merged, set(), set()


# PP's changes to vanilla's build_location_entry, and what becomes of each on CM's entry. A change of PP's that matches
# none stops the build (PP changed the entry again: re-check this rule).
ENTRY_PP_CHANGES = (
    # (name, test on the removed and the added text, what happens on CM's row)
    ("location card wider",
     lambda r, a: _solid(r.splitlines()) == ["size = { 150 48 }"] and re.fullmatch(r"size = \{ \d+ 48 \}", " ".join(_solid(a.splitlines()))) is not None,
     "covered: CM's location card is wider still"),
    ("construction count", lambda r, a: "DataModelFirst(Location.GetCivilConstructions" in a,
     "covered: CM's count reads the first construction the same way (DataModelFirst)"),
    ("production-method slots in columns", lambda r, a: "production_method_slot_circle" in a and "GetBuildingSlots" in a,
     "transplanted: PP's slot columns replace CM's single column, with CM's slot size"),
    ("efficiency in columns",
     lambda r, a: "#efficiency (PP" in a or "(PP: two production methods per column)" in a
     or ("Building.GetProductionMethods" in a and "DataModelSkipFirst" in a),
     "not transplanted: CM's efficiency column (15-high lines, three fit its 46-high row) stays"),
    ("value columns", lambda r, a: "pp_build_location_values" in a,
     "transplanted: PP's value columns after CM's efficiency column; CM's profit column only for non-producing buildings"),
)


def _group_ranges(base: list[str], side: list[str], gap: int = 3) -> list[list[int]]:
    """A side's changes against base as [b0, b1, s0, s1]: changes closer than gap lines joined, and a change of
    closing braces only joined to the change before it (it closes that one's boxes)."""
    groups: list[list[int]] = []
    for b0, b1, s0, s1 in edits(base, side):
        braces = set(_solid(base[b0:b1] + side[s0:s1])) <= {"}"}
        if groups and (b0 - groups[-1][1] <= gap or braces):
            groups[-1][1], groups[-1][3] = b1, s1
        else:
            groups.append([b0, b1, s0, s1])
    return groups


def _change_groups(base: list[str], side: list[str], gap: int = 3) -> list[tuple[str, str]]:
    """A side's change groups as (removed text, added text)."""
    return [("".join(base[b0:b1]), "".join(side[s0:s1])) for b0, b1, s0, s1 in _group_ranges(base, side, gap)]


def _classify(table, removed: str, added: str, where: str, side: str, rule: str):
    """The first entry of a change table whose test matches a change group, or stop."""
    for entry in table:
        if entry[1](removed, added):
            return entry
    raise GuiMergeError(
        f"{where}: {side} changed vanilla's version in a way the rule does not know:\n--- vanilla\n{removed}+++ {side}\n"
        f"{added}Re-check {rule} in src/ppcm/gui_merge.py.")


def _holder(doc: Doc, needles: tuple[str, ...], heads: tuple[str, ...], what: str) -> Stmt:
    """The innermost statement that holds every occurrence of the needles in the text; it must be one of heads."""
    total = [doc.text.count(n) for n in needles]
    if not all(total):
        raise GuiMergeError(f"{doc.label}: {what} not found")
    found = [s for s in doc.walk() if s.block and [doc.raw(s).count(n) for n in needles] == total]
    if not found or found[-1].head[:1] not in [(h,) for h in heads]:
        raise GuiMergeError(f"{doc.label}: {what} is not one {'/'.join(heads)} any more; re-check part_build_entry")
    return found[-1]


def _indent(text: str, offset: int) -> str:
    ls = text.rfind("\n", 0, offset) + 1
    return text[ls:offset] if not text[ls:offset].strip() else ""


def _reindent(block: str, old: str, new: str) -> str:
    return "".join(new + line[len(old):] if line.startswith(old) else line for line in block.splitlines(True))


def part_build_entry(base: str, ours: str, theirs: str, where: str, log: list[str]) -> tuple[str, set[str], set[str]]:
    """build_location_entry (one location row of the build panel). Both mods rebuilt it, so a line merge has no
    meaning: CM replaced the whole row by GlorpUI's 46-high layout (location card with rank button, building limit,
    RGO, market access, wealth and ROI columns, its auto-expand button, the auto-expand checks on every remove and
    upgrade action); PP changed six places of vanilla's row (see ENTRY_PP_CHANGES).

    Rule: CM's row, with PP's changes put back where they are not covered by CM's own:
    - PP's value columns (build cost, payback, profit, tax income) right after CM's efficiency column; CM's profit
      column, which shows the same profit and income, stays only for buildings that produce nothing (its upkeep and
      control lines);
    - PP's production-method slot columns (two per column) in place of CM's single column, with CM's slot size;
    - the expand between the slots and the value columns that CM disabled for vanilla's narrow panel is on again:
      PP's panel is wider and PP's header pushes the value sort buttons right over their columns the same way."""
    done: dict[str, str] = {}
    dropped: set[str] = set()
    for removed, added in _change_groups(base.splitlines(True), ours.splitlines(True)):
        name, _, why = _classify(ENTRY_PP_CHANGES, removed, added, where, "PP", "part_build_entry / ENTRY_PP_CHANGES")
        done[name] = why
        if why.startswith(("covered", "not transplanted")):
            dropped |= identifiers(added) - identifiers(removed)
    dp, dt = Doc(ours, "PP " + where), Doc(theirs, "CM " + where)
    text = theirs
    repl: list[tuple[int, int, str]] = []

    if "production-method slots in columns" in done:
        slots = ("LocationToBuildItem.GetBuildingSlots", "production_method_slot_circle")
        cm_slots = _holder(dt, slots, ("vbox", "hbox"), "CM's slot column")
        pp_slots = _holder(dp, slots, ("hbox", "vbox"), "PP's slot columns")
        circles = [s for s in dt.walk(cm_slots) if s.head == ("production_method_slot_circle", "=")]
        if len(circles) != 1:
            raise GuiMergeError(f"{where}: CM's slot column has {len(circles)} slots, expected one item")
        a, b = dp.span(pp_slots)
        block = dp.text[a:b]
        for s in sorted((s for s in dp.walk(pp_slots) if s.head == ("production_method_slot_circle", "=")), key=lambda s: -s.first):
            x, y = dp.toks[s.first].start - a, dp.toks[s.last].end - a
            block = block[:x] + dt.raw(circles[0]) + block[y:]
        ca, cb = dt.span(cm_slots)
        block = _reindent(block, _indent(dp.text, dp.toks[pp_slots.first].start), _indent(dt.text, dt.toks[cm_slots.first].start))
        repl.append((ca, cb, block))

    if "value columns" in done:
        values = _holder(dp, ("using = pp_build_location_values",), ("hbox",), "PP's value columns")
        # CM's profit column also holds the upkeep and control lines CM moved into it (vanilla had them apart)
        profit = _holder(dt, ("Building.GetUpkeep", "GetBuildingControlNetInLocation"), ("widget",), "CM's profit column")
        siblings = [p for p in dt.walk() if p.block and any(c.first == profit.first for c in dt.inner(p))]
        kids = dt.inner(siblings[0]) if len(siblings) == 1 else []
        at = [n for n, c in enumerate(kids) if c.first == profit.first]
        efficiency = kids[at[0] + 1] if at and at[0] + 1 < len(kids) else None
        if efficiency is None or "BUILDING_PROD_EFFICIENCY" not in dt.raw(efficiency) or efficiency.head[:1] != ("widget",):
            raise GuiMergeError(f"{where}: CM's efficiency column is no longer right after its profit column")
        if any(c.head[:1] == ("visible",) for c in dt.inner(profit)):
            raise GuiMergeError(f"{where}: CM's profit column has its own visible now; re-check part_build_entry")
        open_end = dt.text.find("\n", dt.toks[profit.block[0]].end) + 1
        ind = _indent(dt.text, dt.toks[profit.first].start) + "\t"
        repl.append((open_end, open_end, f'{ind}visible = "[Not(LocationToBuildItem.GetBuildingType.IsProducing)]" '
                                         f"# ppcm: PP's value columns show profit and income for producing buildings\n"))
        _, eb = dt.span(efficiency)
        line = _norm(dp.raw(values))
        comment = dp.text[dp.toks[values.last].end:dp.text.find("\n", dp.toks[values.last].end)].strip()
        repl.append((eb, eb, f"\n{_indent(dt.text, dt.toks[efficiency.first].start)}{line} {comment}\n"))

        disabled = list(re.finditer(r"(?m)^([ \t]*)#[ \t]*expand = \{\}[ \t]*# GlorpUI: disabled[^\n]*$", text))
        if len(disabled) != 1:
            raise GuiMergeError(f"{where}: CM's disabled expand before the value columns not found once ({len(disabled)})")
        m = disabled[0]
        repl.append((m.start(), m.end(), f"{m.group(1)}expand = {{}} # ppcm: on again for PP's wider panel and header (CM: disabled)"))

    for a, b, new in sorted(repl, key=lambda r: (r[0], r[1]), reverse=True):
        text = text[:a] + new + text[b:]
    for name, why in sorted(done.items()):
        log.append(f"{where}: PP's {name}: {why}")
    log.append(f"{where}: base is CM's rebuilt row (both mods rebuilt it)")
    return text, dropped, set()


