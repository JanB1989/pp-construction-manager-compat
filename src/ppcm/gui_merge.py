# the merge


@dataclass
class Record:
    """One merged part, kept for the tests."""

    out: str  # output file
    key: tuple[str, ...]
    base: str
    ours: str  # PP (a copy renamed back to the type it copies)
    theirs: str  # CM
    merged: str
    pp_dropped: set[str] = field(default_factory=set)  # PP identifiers a rule leaves out on purpose
    cm_dropped: set[str] = field(default_factory=set)  # CM identifiers a rule leaves out on purpose
    copy_of: str | None = None


@dataclass
class Result:
    outputs: dict[str, str]
    records: list[Record]
    log: list[str]
    same_path: list[str]


def _copy_of(key: tuple[str, ...], exists) -> tuple[str, ...] | None:
    """The type a pp_ copy copies (constructor gui_compat.py), when that type exists."""
    if key[0] in ("type", "template") and key[1].startswith(COPY_PREFIX):
        orig = (key[0], key[1][len(COPY_PREFIX):])
        if exists(orig):
            return orig
    return None


def _rename_first_line(text: str, old: str, new: str) -> str:
    first, nl, rest = text.partition("\n")
    renamed = re.sub(rf"\b{re.escape(old)}\b", new, first, count=1)
    if renamed == first:
        raise GuiMergeError(f"cannot rename {old} to {new} in: {first.strip()}")
    return renamed + nl + rest


def merge_part(out: str, key: tuple[str, ...], base: str, ours: str, theirs: str, log: list[str],
               copy_of: tuple[str, ...] | None = None) -> Record:
    """Merge one part; a pp_ copy is merged as the type it copies and renamed back."""
    name = copy_of or key
    where = f"{out} {key[0]} {key[1]}"
    if copy_of:
        ours = _rename_first_line(ours, key[1], name[1])
    rule = PART_RULES.get(name)
    if rule:
        merged, pp_dropped, cm_dropped = rule(base, ours, theirs, where, log)
    else:
        tagged = merge3_tagged(base.splitlines(True), ours.splitlines(True), theirs.splitlines(True), where,
                               lambda h: resolve_default(h, log))
        check_nesting(tagged, where)
        merged = "".join(x for x, _ in tagged)
        pp_dropped, cm_dropped = set(), set()
    if copy_of:
        merged = _rename_first_line(merged, name[1], key[1])
    check_gui(merged, where)
    return Record(out, key, base, ours, theirs, merged, pp_dropped, cm_dropped, copy_of[1] if copy_of else None)


def same_path_files(ctx: Context) -> list[str]:
    """GUI files both PP and CM ship: CM's copy replaces PP's, so the patch ships a merged one."""
    return sorted(set(gui_files(ctx.pp_mod)) & set(gui_files(ctx.cm)))


def _other_gui_files(root: Path) -> list[str]:
    """Files other than .gui below the GUI folders and the data-binding folders (scripted widgets, filters, macros)."""
    out = []
    for sub in GUI_DIRS + tuple(f"{d}/data_binding" for d in ("in_game", "main_menu", "loading_screen")):
        base = root / sub
        if base.is_dir():
            out.extend(str(p.relative_to(root)).replace("\\", "/") for p in sorted(base.rglob("*"))
                       if p.is_file() and p.suffix != ".gui")
    return out


def merge_file(ctx: Context, rel: str, van: Vanilla, cmf_keys: set, pp_index: dict, cm_index: dict,
               log: list[str]) -> tuple[str, list[Record]]:
    """A file both mods ship: PP's file with every part merged, CM's new parts added."""
    pp_text = read(ctx.pp_mod / rel)
    dp, dc = Doc(pp_text, f"PP {rel}"), Doc(read(ctx.cm / rel), f"CM {rel}")
    pv = van.parts(rel) if van.has_file(rel) else {}
    pp, pc = dp.parts(), dc.parts()
    records: list[Record] = []
    repl: list[tuple[int, int, str]] = []

    def base_of(key):
        return pv.get(key) or (van.find(key, [rel]) if key[0] in ("type", "template") else None)

    for key, (s, _) in pp.items():
        others = [d.rel for d in pp_index.get(key, []) if d.rel != rel]
        if others:
            raise GuiMergeError(f"{rel}: PP defines {key[0]} {key[1]} here and in {others}; which one is PP's?")
        copy_of = _copy_of(key, lambda k: base_of(k) is not None)
        name = copy_of or key
        elsewhere = [d.rel for d in cm_index.get(name, []) if d.rel != rel]
        if elsewhere:
            raise GuiMergeError(f"{rel}: CM defines {name[0]} {name[1]} in {elsewhere} too; merge that one instead")
        base = base_of(name) or ""
        if name in pc:
            theirs = dc.part_text(pc[name][0])
        elif not base:
            theirs = ""  # PP's own part: CM cannot have changed it
        elif name[0] in ("type", "template") and name in cmf_keys:
            theirs = base  # CM leaves it to CMF's re-declared vanilla version: unchanged
        else:
            raise GuiMergeError(f"{rel}: CM's copy of the file drops vanilla's {name[0]} {name[1]}, and CMF does not "
                                f"re-declare it; decide what the merged file should do with it")
        rec = merge_part(rel, key, base, dp.part_text(s), theirs, log, copy_of)
        records.append(rec)
        a, b = dp.span(s)
        repl.append((a, b, rec.merged))

    added: dict[str | None, list[str]] = {}
    for key, (s, cont) in pc.items():
        if key in pp or key[0] == "types":
            continue
        base = base_of(key) or ""
        if base and _solid(base.splitlines()) == _solid(dc.part_text(s).splitlines()):
            continue  # PP left out a vanilla part that CM keeps unchanged: stays out
        if base:
            raise GuiMergeError(f"{rel}: PP's file leaves out vanilla's {key[0]} {key[1]}, which CM changes")
        if key in pp_index:
            raise GuiMergeError(f"{rel}: CM adds {key[0]} {key[1]} here, which PP defines in {pp_index[key][0].rel}")
        rec = merge_part(rel, key, "", "", dc.part_text(s), log)
        records.append(rec)
        added.setdefault(cont.key[1] if cont else None, []).append(rec.merged)
        log.append(f"{rel}: CM's new {key[0]} {key[1]} added")
    blocks = {s.key[1]: s for s in dp.stmts if s.key[0] == "types"}
    tail = []
    for block_name, texts in sorted(added.items(), key=lambda x: str(x[0])):
        if block_name is None:
            tail.extend(texts)
        elif block_name in blocks:
            close = dp.toks[blocks[block_name].last].start
            at = dp.text.rfind("\n", 0, close) + 1
            repl.append((at, at, "".join(texts)))
        else:
            tail.append(f"types {block_name} {{\n" + "".join(texts) + "}\n")
    text = pp_text
    for a, b, new in sorted(repl, key=lambda r: (r[0], r[1]), reverse=True):
        text = text[:a] + new + text[b:]
    if tail:
        text = text.rstrip("\n") + "\n\n" + "\n".join(tail)
    text = _header(f"{rel}: Prosper or Perish's file with Construction Manager's changes", rel, log) + text
    check_gui(text, f"merged {rel}")
    return bom(text), records


def _header(what: str, rel: str, log: list[str]) -> str:
    """The generated-file note, with the rules that resolved something in this file."""
    notes = [" ".join(line[len(rel):].lstrip(": ").split()) for line in log if line.startswith(rel)]
    return HEADER.format(what=what) + "".join(f"# - {n}\n" for n in notes)


def merge_all(ctx: Context) -> Result:
    log: list[str] = []
    van = Vanilla(ctx.vanilla)
    pp_index, cm_index = index(ctx.pp_mod, "PP"), index(ctx.cm, "CM")
    cmf_keys = set(index(ctx.cmf, "CMF"))
    for label, idx in (("PP", pp_index), ("CM", cm_index)):
        for key, defs in idx.items():
            if len(defs) > 1:
                raise GuiMergeError(f"{label} defines {key[0]} {key[1]} in {[d.rel for d in defs]}; which one wins?")
    same = same_path_files(ctx)
    others = sorted(set(_other_gui_files(ctx.pp_mod)) & set(_other_gui_files(ctx.cm)))
    if others:
        raise GuiMergeError(f"PP and CM both ship {others} (not .gui: scripted widgets, filters, macros?); CM's copy "
                            f"replaces PP's. Merge them in src/ppcm/gui_merge.py.")
    outputs: dict[str, str] = {}
    records: list[Record] = []
    for rel in same:
        outputs[rel], recs = merge_file(ctx, rel, van, cmf_keys, pp_index, cm_index, log)
        records.extend(recs)

    # types and templates both mods define in different files (and PP's copies of types CM changes)
    shared: list[tuple[tuple[str, ...], Def, tuple[str, ...] | None]] = []
    for key, (pdef,) in sorted(pp_index.items()):
        if pdef.rel in same:
            continue
        copy_of = _copy_of(key, lambda k: k in cm_index)
        name = copy_of or key
        if name not in cm_index:
            continue
        cdef = cm_index[name][0]
        if cdef.rel in same:
            raise GuiMergeError(f"CM changes {name[0]} {name[1]} in {cdef.rel}, PP in {pdef.rel}: not handled")
        if not copy_of and _solid(pdef.text.splitlines()) == _solid(cdef.text.splitlines()):
            continue  # the same in both: whichever wins is right
        shared.append((key, pdef, copy_of))
    texts = {"type": [], "template": []}
    for key, pdef, copy_of in shared:
        name = copy_of or key
        cdef = cm_index[name][0]
        base = van.find(name, [pdef.rel, cdef.rel]) or ""
        if copy_of and _solid(cdef.text.splitlines()) == _solid(base.splitlines()):
            continue  # CM leaves the copied type as vanilla: PP's copy stays as it is
        rec = merge_part(MERGED_TYPES, key, base, pdef.text, cdef.text, log, copy_of)
        records.append(rec)
        texts[key[0]].append(rec.merged)
        log.append(f"{MERGED_TYPES}: {key[0]} {key[1]} merged (PP {pdef.rel}, CM {cdef.rel})")
    if texts["type"] or texts["template"]:
        body = _header("the types and templates both mods define in different files", MERGED_TYPES, log)
        if texts["type"]:
            body += f"\ntypes {MERGED_TYPES_BLOCK} {{\n" + "\n".join(texts["type"]) + "}\n"
        if texts["template"]:
            body += "\n" + "\n".join(texts["template"])
        check_gui(body, MERGED_TYPES)
        outputs[MERGED_TYPES] = bom(body)
    return Result(outputs, records, log, same)


def build(ctx: Context) -> dict[str, str]:
    return merge_all(ctx).outputs
