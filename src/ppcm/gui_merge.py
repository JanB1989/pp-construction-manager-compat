# conflict rules for any part (each returns the merged lines, or None when it does not apply)


def _statements_of(lines: list[str]) -> list[str] | None:
    """The attribute keys of a run of whole statements (key = value, blockoverride "x", block "x"), or None when the
    lines are not whole statements."""
    text = "".join(lines)
    try:
        d = Doc(text, "hunk")
    except GuiMergeError:
        return None
    keys = []
    for s in d.stmts:
        if not s.block and len(s.head) == 3 and s.head[1] == "=":
            keys.append(s.head[0])  # an attribute
        elif s.block and len(s.head) == 2 and s.head[0] in ("blockoverride", "block"):
            keys.append(" ".join(s.head))  # a named override slot
    return keys


def rule_separate_lines(h: Hunk) -> list[tuple[str, str]] | None:
    """PP and CM change different lines that only touch (no line changed by both, no insertion inside the other's
    change): apply both, in vanilla's line order."""
    eo, et = edits(h.base, h.ours), edits(h.base, h.theirs)
    if not eo or not et:
        return None
    for b0, b1, _, _ in eo:
        for c0, c1, _, _ in et:
            if b0 == b1 == c0 == c1:
                return None  # both insert at the same point: rule_both_insert
            if max(b0, c0) < min(b1, c1):
                return None  # a line both changed
            if (b0 == b1 and c0 < b0 < c1) or (c0 == c1 and b0 < c0 < b1):
                return None  # an insertion inside the other's change
    return _compose(h, eo, et)


def rule_both_insert(h: Hunk) -> list[tuple[str, str]] | None:
    """Both insert whole statements at the same point (a child or an attribute each, for example in the same box):
    keep both, PP's first. Not when both set the same attribute or the same override slot (a real conflict)."""
    eo, et = edits(h.base, h.ours), edits(h.base, h.theirs)
    if not eo or not et:
        return None
    for b0, b1, s0, s1 in eo:
        for c0, c1, t0, t1 in et:
            if max(b0, c0) < min(b1, c1) or (b0 == b1 and c0 < b0 < c1) or (c0 == c1 and b0 < c0 < b1):
                return None
            if b0 == b1 == c0 == c1:
                ko, kt = _statements_of(h.ours[s0:s1]), _statements_of(h.theirs[t0:t1])
                if ko is None or kt is None or set(ko) & set(kt):
                    return None
    return _compose(h, eo, et)


def _compose(h: Hunk, eo, et) -> list[tuple[str, str]]:
    """Apply both sides' edits to the hunk's base lines (at the same insertion point PP's goes first)."""
    out: list[tuple[str, str]] = []
    allx = sorted([(b0, b1, 0, h.ours[s0:s1]) for b0, b1, s0, s1 in eo] + [(c0, c1, 1, h.theirs[t0:t1]) for c0, c1, t0, t1 in et],
                  key=lambda e: (e[0], e[1] > e[0], e[2]))
    i = 0
    for b0, b1, side, lines in allx:
        out.extend((x, "=") for x in h.base[i:b0])
        out.extend((x, ("pp", "cm")[side]) for x in lines)
        i = max(i, b1)
    out.extend((x, "=") for x in h.base[i:])
    return out


HUNK_RULES = (rule_separate_lines, rule_both_insert)


def resolve_default(h: Hunk, log: list[str]) -> list[tuple[str, str]]:
    for rule in HUNK_RULES:
        out = rule(h)
        if out is not None:
            log.append(f"{h.where}, vanilla line {h.base_start + 1}: {rule.__name__} ({' '.join(rule.__doc__.split(':')[0].split())})")
            return out
    raise GuiMergeError(_describe(h))


