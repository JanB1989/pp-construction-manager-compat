@dataclass(frozen=True)
class Tok:
    kind: str  # "{", "}", "=", "str", "word"
    start: int
    end: int


_WORD = re.compile(r'[^\s{}=#"]+')


def tokens(text: str, label: str = "") -> list[Tok]:
    """The tokens of a GUI text. Comments are skipped; strings may span lines (GUI strings have no escapes)."""
    out: list[Tok] = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == "#":
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif c == '"':
            j = text.find('"', i + 1)
            if j < 0:
                raise GuiMergeError(f"{label}: unterminated string at line {text.count(chr(10), 0, i) + 1}")
            out.append(Tok("str", i, j + 1))
            i = j + 1
        elif c in "{}=":
            out.append(Tok(c, i, i + 1))
            i += 1
        elif c.isspace():
            i += 1
        else:
            m = _WORD.match(text, i)
            out.append(Tok("word", i, m.end()))
            i = m.end()
    return out


@dataclass
class Stmt:
    head: tuple[str, ...]  # the words before the block or the value, "=" included: ("type", "x", "=", "hbox")
    first: int  # token index of the first token
    last: int  # token index of the last token (the closing brace of a block)
    block: tuple[int, int] | None = None  # token indices of the braces
    children: list["Stmt"] = field(default_factory=list)  # the types of a types block
    key: tuple[str, ...] = ()


class Doc:
    """A parsed GUI text: tokens, brace matches, top-level statements; types blocks are opened one level."""

    def __init__(self, text: str, label: str):
        self.text = text
        self.label = label
        self.toks = tokens(text, label)
        self.match: dict[int, int] = {}
        stack: list[int] = []
        for k, t in enumerate(self.toks):
            if t.kind == "{":
                stack.append(k)
            elif t.kind == "}":
                if not stack:
                    raise GuiMergeError(f"{label}: unmatched '}}' at line {self.line(t.start)}")
                o = stack.pop()
                self.match[o] = k
                self.match[k] = o
        if stack:
            raise GuiMergeError(f"{label}: unclosed '{{' at line {self.line(self.toks[stack[-1]].start)}")
        self.stmts = self.statements(0, len(self.toks))
        for s in self.stmts:
            if len(s.head) == 1 and not s.block:
                raise GuiMergeError(f"{label}: stray '{s.head[0]}' at line {self.line(self.toks[s.first].start)}")
        counts: Counter = Counter()
        for s in self.stmts:
            self._key(s, counts)
            if s.key[0] == "types":
                s.children = self.inner(s)
                for c in s.children:
                    self._key(c, counts)

    def line(self, offset: int) -> int:
        return self.text.count("\n", 0, offset) + 1

    def word(self, k: int) -> str:
        t = self.toks[k]
        return self.text[t.start:t.end]

    def statements(self, k0: int, k1: int) -> list[Stmt]:
        """The statements between token indices k0 and k1 (one nesting level)."""
        out: list[Stmt] = []
        k = k0
        while k < k1:
            first = k
            head: list[str] = []
            while True:
                if k >= k1:
                    if not head or "=" in head:
                        raise GuiMergeError(f"{self.label}: statement without value at line {self.line(self.toks[first].start)}")
                    out.extend(Stmt((w,), first + n, first + n) for n, w in enumerate(head))  # a value list: { 0 0 }
                    break
                t = self.toks[k]
                if t.kind == "{":
                    close = self.match[k]
                    out.append(Stmt(tuple(head), first, close, (k, close)))
                    k = close + 1
                    break
                if t.kind == "}":
                    raise GuiMergeError(f"{self.label}: unexpected '}}' at line {self.line(t.start)}")
                if t.kind == "=":
                    head.append("=")
                    k += 1
                    if k < k1 and self.toks[k].kind == "{":
                        continue
                    if k >= k1 or self.toks[k].kind in "}=":
                        raise GuiMergeError(f"{self.label}: '=' without value at line {self.line(t.start)}")
                    head.append(self.word(k))
                    k += 1
                    if k < k1 and self.toks[k].kind == "{":
                        continue
                    out.append(Stmt(tuple(head), first, k - 1))
                    break
                head.append(self.word(k))
                k += 1
        return out

    def inner(self, s: Stmt) -> list[Stmt]:
        return self.statements(s.block[0] + 1, s.block[1]) if s.block else []

    def walk(self, s: Stmt | None = None):
        """Every statement below s (pre-order), or of the whole text."""
        for c in self.inner(s) if s else self.stmts:
            yield c
            yield from self.walk(c)

    def _key(self, s: Stmt, counts: Counter) -> None:
        h = s.head
        if len(h) >= 2 and h[0] == "type" and s.block:
            s.key = ("type", h[1])
        elif len(h) == 2 and h[0] == "template" and s.block:
            s.key = ("template", h[1])
        elif len(h) == 2 and h[0] == "types" and s.block:
            s.key = ("types", h[1])
        elif s.block and h and h[-1] == "=":
            name = self._name(s)
            if name:
                s.key = ("window", name)
            else:
                counts[h[0]] += 1
                s.key = ("element", f"{h[0]}#{counts[h[0]]}")
        else:
            label = " ".join(h)
            counts[label] += 1
            s.key = ("other", f"{label}#{counts[label]}")

    def _name(self, s: Stmt) -> str | None:
        """A window's name: its own name, or the one its menu template sets (blockoverride "menu_setup")."""
        children = self.inner(s)
        for c in children:
            if c.head[:2] == ("name", "=") and len(c.head) == 3:
                return c.head[2].strip('"')
        for c in children:
            if c.head[:1] == ("blockoverride",) and c.block:
                for g in self.inner(c):
                    if g.head[:2] == ("name", "=") and len(g.head) == 3:
                        return g.head[2].strip('"')
        return None

    def span(self, s: Stmt) -> tuple[int, int]:
        """Whole lines of a statement: from its line start (when only blanks precede it) to its line end."""
        a = self.toks[s.first].start
        b = self.toks[s.last].end
        ls = self.text.rfind("\n", 0, a) + 1
        if not self.text[ls:a].strip():
            a = ls
        le = self.text.find("\n", b)
        le = len(self.text) if le < 0 else le + 1
        rest = self.text[b:le].strip()
        if not rest or rest.startswith("#"):
            b = le
        return a, b

    def part_text(self, s: Stmt) -> str:
        a, b = self.span(s)
        t = self.text[a:b]
        return t if t.endswith("\n") else t + "\n"

    def raw(self, s: Stmt) -> str:
        return self.text[self.toks[s.first].start:self.toks[s.last].end]

    def parts(self) -> dict[tuple[str, ...], tuple[Stmt, Stmt | None]]:
        """key -> (statement, its types block or None) for every type, template and top-level element."""
        out: dict[tuple[str, ...], tuple[Stmt, Stmt | None]] = {}
        for s in self.stmts:
            for c, cont in ([(c, s) for c in s.children] if s.key[0] == "types" else [(s, None)]):
                if c.key in out:
                    raise GuiMergeError(f"{self.label}: {c.key[0]} {c.key[1]} is defined twice")
                out[c.key] = (c, cont)
        return out


def check_gui(text: str, label: str) -> Doc:
    """Parse an output (balanced braces, closed strings, whole statements) and refuse conflict markers."""
    for n, line in enumerate(text.split("\n"), 1):
        if re.match(r"(<{7}|={7}|>{7}|\|{7})( |$)", line):
            raise GuiMergeError(f"{label}: conflict marker at line {n}")
    return Doc(text.lstrip("﻿"), label)


_IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


def identifiers(text: str) -> set[str]:
    """Every name in a GUI text outside comments: widget and type names, loc keys, data-binding functions, scripted
    GUI and variable names (inside strings too)."""
    out: set[str] = set()
    for t in tokens(text):
        if t.kind in ("word", "str"):
            out.update(_IDENT.findall(text[t.start:t.end]))
    return out


