@dataclass(frozen=True)
class Def:
    key: tuple[str, ...]
    rel: str  # the file (relative to the mod or game root)
    text: str  # whole lines


def gui_files(root: Path) -> list[str]:
    out = []
    for sub in GUI_DIRS:
        base = root / sub
        if base.is_dir():
            out.extend(str(p.relative_to(root)).replace("\\", "/") for p in sorted(base.rglob("*.gui")))
    return out


def index(root: Path, label: str) -> dict[tuple[str, ...], list[Def]]:
    """key -> definitions of every type and template in a mod's GUI files."""
    out: dict[tuple[str, ...], list[Def]] = {}
    for rel in gui_files(root):
        d = Doc(read(root / rel), f"{label} {rel}")
        for key, (s, _) in d.parts().items():
            if key[0] in ("type", "template"):
                out.setdefault(key, []).append(Def(key, rel, d.part_text(s)))
    return out


class Vanilla:
    """The game's definitions, looked up when needed (the base of every merge)."""

    def __init__(self, root: Path):
        self.root = root
        self.docs: dict[str, dict] = {}
        self.names: dict[tuple[str, str], list[str]] | None = None  # (kind, name) -> game files naming it

    def roots(self) -> list[Path]:
        return [self.root] + sorted(p for p in (self.root / "dlc").glob("*") if p.is_dir())

    def parts(self, rel: str) -> dict:
        """The parts of a game file, the last copy (base game, then the DLCs) winning."""
        if rel not in self.docs:
            found: dict = {}
            for r in self.roots():
                if (r / rel).is_file():
                    d = Doc(read(r / rel), f"vanilla {rel}")
                    found.update({k: d.part_text(s) for k, (s, _) in d.parts().items()})
            self.docs[rel] = found
        return self.docs[rel]

    def has_file(self, rel: str) -> bool:
        return any((r / rel).is_file() for r in self.roots())

    def find(self, key: tuple[str, ...], prefer: list[str]) -> str | None:
        """Vanilla's text of a type or template: from the preferred files first, else any game GUI file."""
        for rel in prefer:
            if self.has_file(rel) and key in self.parts(rel):
                return self.parts(rel)[key]
        if self.names is None:
            self.names = {}
            pattern = re.compile(r"(?m)^[ \t]*(type|template)[ \t]+(\w+)")
            for r in self.roots():
                for rel in gui_files(r):
                    for m in pattern.finditer(read(r / rel)):
                        files = self.names.setdefault((m.group(1), m.group(2)), [])
                        if rel not in files:
                            files.append(rel)
        hit = None
        for rel in self.names.get((key[0], key[1]), []):
            if key in self.parts(rel):
                hit = self.parts(rel)[key]
        return hit


