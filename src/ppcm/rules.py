"""Prosper or Perish's food, Granary, improvement and logistics rules as Construction Manager features.

The rules are Prosper or Perish's Construction Plan rules (constructor branch location-profiles, Jan 2026-11-08/09);
``plan_core.py`` is that branch's generator (construction_plan.py), kept as it is. This step writes the parts that
follow Prosper or Perish's buildings and goods, renamed from the plan's ``pp_cplan_`` to ``ppcm_`` so they never meet
the plan's own names:

* ``scripted_effects/ppcm_generated.txt``: the farm, Victualling Yard, kitchen, Tavern, Granary, Grange, logistics and
  improvement pickers and the build cost lookup (``ppcm_btype_data``);
* ``script_values/ppcm_generated.txt``: the rules' numbers ([rules] in ppcm.toml), the farm and improvement estimates,
  the construction goods' price factors, this year's harvest and the access blacklist;
* ``scripted_triggers/ppcm_generated.txt``: the construction goods checks and the food queue check.

The engine of the rules (the province pass, the staging into Construction Manager's queues, the Granary and
improvement passes) is hand-written in ``mod/`` (``ppcm_*.txt``). Construction Manager's own files that must learn of
the new features are patched in ``cm_patch.py``.
"""

from __future__ import annotations

import re
import tomllib
from pathlib import Path

from ppcm import cm_patch
from ppcm import plan_core as plan
from ppcm.context import REPO, Context, bom

CONFIG = REPO / "ppcm.toml"
EFFECTS = "in_game/common/scripted_effects/ppcm_generated.txt"
VALUES = "in_game/common/script_values/ppcm_generated.txt"
TRIGGERS = "in_game/common/scripted_triggers/ppcm_generated.txt"
HEADER = "# Generated by ppcm build (rules.py) from Prosper or Perish's buildings and ppcm.toml; do not edit by hand.\n"


def load_config(path: Path = CONFIG) -> plan.Config:
    data = tomllib.loads(path.read_text(encoding="utf-8"))["rules"]
    return plan.Config(
        reserve_gold=0,
        access_threshold=int(data["access_threshold"]),
        farm_sites_per_province=int(data["farm_sites_per_province"]),
        kitchens=tuple(data["kitchens"]),
        taverns=tuple(data["taverns"]),
        granaries=tuple(data["granaries"]),
        logistics_order=tuple(data["logistics_order"]),
        hidden_goods=frozenset(data["hidden_goods"]),
        hungry_months=int(data["hungry_months"]),
        granges=tuple(data["granges"]),
        yards=tuple(data["yards"]),
        granary_capacity_months=int(data["granary_capacity_months"]),
        granary_fill_pct=int(data["granary_fill_pct"]),
        grange_surplus_pct=int(data["grange_surplus_pct"]),
        famine_months=int(data["famine_months"]),
        yard_payback_years=int(data["yard_payback_years"]),
        tavern_victuals=float(data["tavern_victuals"]),
        improve_fill_pct=int(data["improve_fill_pct"]),
        construction_goods_months=int(data["construction_goods_months"]),
        access_blacklist=tuple(data["access_blacklist"]),
    )


def rename(text: str) -> str:
    """The plan's names become the patch's (pp_cplan_x -> ppcm_x); the generated header is the patch's."""
    text = text.replace(plan.HEADER, "").replace("﻿", "")
    return text.replace("pp_cplan_", "ppcm_")


def _constants(config: plan.Config) -> str:
    rows = (
        ("ppcm_hungry_months", config.hungry_months,
         "Province scope: hungry = a normal year leaves less than this many months in the store a year from now."),
        ("ppcm_famine_months", config.famine_months, "Any scope: the famine line, months in the store a year from now."),
        ("ppcm_granary_cap", config.granary_capacity_months,
         "Any scope: a Granary while the store can hold fewer months of consumption than this."),
        ("ppcm_granary_fill", config.granary_fill_pct, "Any scope: a Granary only while the store is at least this full, in %."),
        ("ppcm_grange_surplus", config.grange_surplus_pct,
         "Any scope: a Grange where a full store still gains this % of consumption a month."),
        ("ppcm_yard_payback", config.yard_payback_years,
         "Any scope: Victualling Yard levels while they pay back within this many years."),
        ("ppcm_tavern_victuals", config.tavern_victuals, "Any scope: victuals a Tavern's market must hold."),
        ("ppcm_farm_sites", config.farm_sites_per_province, "Any scope: locations tried per province for a staple food maker."),
        ("ppcm_improve_default", config.improve_fill_pct,
         "Any scope: the improvement line's default, population in % of capacity (the setting starts there)."),
        ("ppcm_access_default", config.access_threshold,
         "Any scope: the logistics line's default, market access in % (the setting starts there)."),
    )
    return "\n# ---- The rules' numbers (ppcm.toml [rules]) ----\n\n" + "".join(
        plan._constant(name, value, comment) for name, value, comment in rows)


def generate(ctx: Context) -> dict[str, str]:
    """The three generated script files (renamed), and what was found, for the tests."""
    from prosper_or_perish_constructor import arable_land_bar, crop_farms, market_short_weight

    config = load_config()
    mod_root, vanilla_root, repo = ctx.pp_mod, ctx.vanilla.parent, ctx.pp_repo
    database = plan._database(mod_root, vanilla_root, plan.BUILDING_TYPES)
    costs, demands = plan.building_costs(mod_root, vanilla_root, database)
    bounds = plan.price_impact_bounds(mod_root, vanilla_root)

    table = crop_farms.load_crop_table(repo)
    goods_by_building = crop_farms.crop_building_goods(table)
    lines: dict[str, list[str]] = {}
    for building in crop_farms.crop_buildings(table):
        lines.setdefault(building.split("_", 1)[0], []).append(building)
    farm_goods = {line: goods_by_building[tiers[0]] for line, tiers in lines.items()}
    short = market_short_weight.apply(repo / "constructor.toml", mod_root, vanilla_root, write=False)
    food_lines, _ = plan.staple_food_lines(repo, mod_root, lines, farm_goods, short.main_good,
                                           set(config.kitchens) | set(config.taverns))
    food_buildings = [b for tiers in food_lines.values() for b in tiers]
    improvements = [(b.key, b.land) for b in arable_land_bar.model(mod_root, vanilla_root / "game").improvements]
    improve_values, improve_effects = plan.render_improvements(improvements, costs)

    wanted = food_buildings + [key for key, _ in improvements]
    wanted += [*config.kitchens, *config.taverns, *config.granaries, *config.granges, *config.yards,
               *config.logistics_order]
    missing = sorted({name for name in wanted if name not in costs})
    if missing:
        raise SystemExit(f"buildings Prosper or Perish does not define: {missing}")

    values = (_constants(config) + rename(plan.render_price_factors(demands, bounds))
              + rename(plan.render_baseline_values(
                  config, food_lines, plan.farm_recipes(repo, food_buildings), plan.harvest_rates(mod_root),
                  plan.peasant_food_consumption(mod_root, vanilla_root),
                  plan.access_modifier_amounts(mod_root, vanilla_root, config.access_blacklist), costs))
              + rename(improve_values))
    effects = rename(plan.render_effects(config, food_lines, costs)) + rename(improve_effects)
    # the plan window's flag list is not part of these rules
    effects = _drop_block(effects, "ppcm_declare_flags")
    triggers = rename(plan.render_triggers(demands, food_buildings + list(config.taverns),
                                           config.construction_goods_months))
    return {
        EFFECTS: bom(HEADER + effects),
        VALUES: bom(HEADER + values),
        TRIGGERS: bom(HEADER + triggers),
    }


def _drop_block(text: str, name: str) -> str:
    """Removes the top-level block `name = { ... }` and the comment lines right above it."""
    match = re.search(rf"(?m)^{name} = \{{\n.*?^\}}\n", text, re.DOTALL)
    if not match:
        return text
    start = match.start()
    while True:
        previous = text.rfind("\n", 0, start - 1)
        line = text[previous + 1:start]
        if line.startswith("#"):
            start = previous + 1
        else:
            break
    return text[:start] + text[match.end():]


def build(ctx: Context) -> dict[str, str]:
    return {**generate(ctx), **cm_patch.build(ctx)}
